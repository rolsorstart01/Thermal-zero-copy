class WorkloadGenerator:
    """
    Generates synthetic inference workloads with configurable patterns.
    """
    
    def __init__(
        self,
        context_sharing_ratio: float = 0.7,
        seed: Optional[int] = None
    ):
        """
        Initialize workload generator.
        
        Args:
            context_sharing_ratio: Fraction of requests that share context
            seed: Random seed for reproducibility
        """
        self.context_sharing_ratio = context_sharing_ratio
        self.rng = np.random.default_rng(seed)
        
        # Predefined contexts for sharing
        self.shared_contexts = [
            ("company-handbook", "Company employee handbook with policies and procedures..."),
            ("api-docs", "API documentation for the platform including endpoints..."),
            ("code-base", "Source code repository for the main application..."),
            ("research-paper", "Research paper on transformer architectures..."),
            ("legal-docs", "Legal documents and terms of service..."),
        ]
        
        self.request_counter = 0
    
    def generate_request(self) -> InferenceRequest:
        """Generate a single inference request."""
        self.request_counter += 1
        
        # Decide if this request uses shared context
        use_shared = self.rng.random() < self.context_sharing_ratio
        
        if use_shared:
            ctx_id, ctx_content = self.rng.choice(self.shared_contexts)
        else:
            ctx_id = f"unique-{self.request_counter}"
            ctx_content = f"Unique content for request {self.request_counter}..."
        
        # Generate prompt variations
        prompts = [
            f"Explain the key points in {ctx_id}.",
            f"What does {ctx_id} say about security?",
            f"Summarize {ctx_id}.",
            f"Find information about authentication in {ctx_id}.",
            f"How does {ctx_id} handle errors?",
        ]
        
        prompt = self.rng.choice(prompts)
        
        # Estimate workload size
        size_choice = self.rng.choice(["SMALL", "MEDIUM", "LARGE"], p=[0.5, 0.35, 0.15])
        max_tokens = {"SMALL": 128, "MEDIUM": 512, "LARGE": 2048}[size_choice]
        
        return InferenceRequest(
            request_id=f"req_{self.request_counter:06d}",
            prompt=prompt,
            context=ctx_id,
            max_tokens=max_tokens,
            priority=self.rng.integers(1, 11),
            user_id=f"user_{self.rng.integers(1, 100)}"
        )
    
    def generate_batch(self, count: int) -> List[InferenceRequest]:
        """Generate a batch of requests."""
        return [self.generate_request() for _ in range(count)]


class SimulationRunner:
    """
    Runs comparison simulations between baseline and ThermoCache schedulers.
    """
    
    def __init__(
        self,
        cluster: GPUClusterSimulator,
        context_sharing_ratio: float = 0.7,
        seed: Optional[int] = None
    ):
        """
        Initialize simulation runner.
        
        Args:
            cluster: GPU cluster simulator
            context_sharing_ratio: Context sharing ratio
            seed: Random seed
        """
        self.cluster = cluster
        self.context_sharing_ratio = context_sharing_ratio
        self.seed = seed
        
        self.workload_gen = WorkloadGenerator(context_sharing_ratio, seed)
    
    async def run_baseline_simulation(
        self,
        num_requests: int
    ) -> Tuple[SystemMetrics, List[dict]]:
        """
        Run simulation with baseline scheduler.
        
        Args:
            num_requests: Number of requests to process
            
        Returns:
            Tuple of (final metrics, decision log)
        """
        scheduler = BaselineScheduler()
        decisions = []
        
        # Reset cluster state
        await self._reset_cluster()
        
        for i in range(num_requests):
            request = self.workload_gen.generate_request()
            metrics = self.cluster.get_all_metrics()
            
            workload_size = request.estimate_workload_size()
            decision = scheduler.select_gpu(
                gpus=metrics,
                workload_size=workload_size,
                context_id=None,  # Baseline doesn't use context
                request_id=request.request_id
            )
            
            # Update GPU state
            vram_increase = 0.1 if i % 10 == 0 else 0  # Occasional VRAM increase
            util_increase = 2 if i % 5 == 0 else 0
            
            self.cluster.update_gpu_workload(
                decision.selected_gpu,
                util_increase,
                vram_increase
            )
            
            # Simulate thermal effects
            self.cluster.simulate_workload_tick()
            
            decisions.append({
                "request_id": request.request_id,
                "gpu": decision.selected_gpu,
                "temp": decision.temperature,
                "context_reused": False
            })
            
            self.cluster.request_count += 1
        
        return self.cluster.get_system_metrics(), decisions
    
    async def run_thermocache_simulation(
        self,
        num_requests: int
    ) -> Tuple[SystemMetrics, List[dict]]:
        """
        Run simulation with ThermoCache scheduler.
        
        Args:
            num_requests: Number of requests to process
            
        Returns:
            Tuple of (final metrics, decision log)
        """
        context_cache = ContextCache()
        thermal_predictor = ThermalPredictor()
        scheduler = ThermalAwareScheduler(context_cache, thermal_predictor)
        decisions = []
        
        # Reset cluster state
        await self._reset_cluster()
        
        for i in range(num_requests):
            request = self.workload_gen.generate_request()
            metrics = self.cluster.get_all_metrics()
            
            # Register or reuse context
            ctx_metadata, is_new = await context_cache.register_or_reuse(
                content=request.context or request.prompt,
                gpu_location=0,  # Will be updated by scheduler
                context_id=request.context
            )
            
            workload_size = request.estimate_workload_size()
            decision = await scheduler.select_gpu(
                gpus=metrics,
                workload_size=workload_size,
                context_id=request.context,
                request_id=request.request_id
            )
            
            # Update context location
            if ctx_metadata.gpu_location != decision.selected_gpu:
                await context_cache.index.update_gpu_location(
                    request.context, decision.selected_gpu
                )
                self.cluster.add_context_to_gpu(
                    decision.selected_gpu,
                    request.context or "default",
                    0.1
                )
            
            # Update GPU state
            vram_increase = 0.05 if is_new else 0.01  # Less VRAM for reused context
            util_increase = 2 if i % 5 == 0 else 0
            
            self.cluster.update_gpu_workload(
                decision.selected_gpu,
                util_increase,
                vram_increase,
                contexts=[request.context] if request.context else []
            )
            
            # Update thermal predictor
            for m in metrics:
                thermal_predictor.update_gpu_temperature(m.gpu_id, m.temperature)
            
            # Simulate thermal effects
            self.cluster.simulate_workload_tick()
            
            decisions.append({
                "request_id": request.request_id,
                "gpu": decision.selected_gpu,
                "temp": decision.temperature,
                "context_reused": decision.context_reused,
                "score": decision.score
            })
            
            self.cluster.request_count += 1
        
        return self.cluster.get_system_metrics(context_cache), decisions
    
    async def _reset_cluster(self):
        """Reset cluster to initial state."""
        for gpu in self.cluster.gpus.values():
            gpu.temperature = gpu.base_temp
            gpu.utilization = 0
            gpu.vram_used = 0
            gpu.contexts = []
            gpu.workload_queue = []
        
        self.cluster.request_count = 0
        self.cluster.start_time = datetime.now()
        
        # Reset workload generator
        self.workload_gen = WorkloadGenerator(self.context_sharing_ratio, self.seed)
    
    async def run_comparison(
        self,
        num_requests: int = 1000
    ) -> dict:
        """
        Run full comparison between baseline and ThermoCache.
        
        Args:
            num_requests: Number of requests per simulation
            
        Returns:
            Comparison results dictionary
        """
        logger.info(f"Starting comparison simulation with {num_requests} requests")
        
        # Run baseline
        logger.info("Running baseline simulation...")
        baseline_metrics, baseline_decisions = await self.run_baseline_simulation(num_requests)
        
        # Run ThermoCache
        logger.info("Running ThermoCache simulation...")
        thermocache_metrics, thermocache_decisions = await self.run_thermocache_simulation(num_requests)
        
        # Calculate comparison metrics
        comparison = {
            "temperature_reduction": baseline_metrics.average_temperature - thermocache_metrics.average_temperature,
            "peak_temperature_reduction": baseline_metrics.peak_temperature - thermocache_metrics.peak_temperature,
            "vram_savings_percent": (
                (baseline_metrics.total_vram_used - thermocache_metrics.total_vram_used) 
                / baseline_metrics.total_vram_used * 100 
                if baseline_metrics.total_vram_used > 0 else 0
            ),
            "context_reuse_rate": thermocache_metrics.context_hit_rate,
            "thermal_distribution_improvement": self._calculate_thermal_distribution_improvement(
                baseline_decisions, thermocache_decisions
            )
        }
        
        return {
            "baseline": baseline_metrics,
            "thermocache": thermocache_metrics,
            "comparison": comparison,
            "baseline_decisions": baseline_decisions[:100],  # Sample
            "thermocache_decisions": thermocache_decisions[:100]
        }
    
    def _calculate_thermal_distribution_improvement(
        self,
        baseline_decisions: List[dict],
        thermocache_decisions: List[dict]
    ) -> float:
        """Calculate improvement in thermal distribution."""
        if not baseline_decisions or not thermocache_decisions:
            return 0.0
        
        baseline_temps = [d["temp"] for d in baseline_decisions]
        thermocache_temps = [d["temp"] for d in thermocache_decisions]
        
        # Lower variance = better distribution
        baseline_var = np.var(baseline_temps)
        thermocache_var = np.var(thermocache_temps)
        
        if baseline_var == 0:
            return 0.0
        
        return (baseline_var - thermocache_var) / baseline_var * 100
