class SimulatedGPU:
    """
    Simulates a single GPU with thermal dynamics and workload processing.
    """
    
    def __init__(
        self,
        gpu_id: int,
        rack_id: int,
        vram_total: float = 24.0,
        base_temp: float = 45.0,
        cooling_efficiency: float = 1.0
    ):
        """
        Initialize simulated GPU.
        
        Args:
            gpu_id: GPU identifier
            rack_id: Rack identifier
            vram_total: Total VRAM in GB
            base_temp: Base/idle temperature
            cooling_efficiency: Cooling efficiency factor (0.5-1.5)
        """
        self.gpu_id = gpu_id
        self.rack_id = rack_id
        self.vram_total = vram_total
        self.base_temp = base_temp
        self.cooling_efficiency = cooling_efficiency
        
        # Current state
        self.temperature = base_temp
        self.utilization = 0.0
        self.vram_used = 0.0
        self.power_draw = 50.0  # Idle power
        self.contexts: List[str] = []
        self.workload_queue: List[str] = []
        
        # Thermal dynamics parameters
        self.thermal_mass = 10.0  # Higher = slower temp change
        self.load_heating_coefficient = 0.4  # °C per % utilization
        self.ambient_cooling_coefficient = 0.1 * cooling_efficiency
    
    def update_state(
        self,
        new_utilization: float,
        new_vram_used: float,
        contexts: List[str],
        ambient_temp: float = 25.0
    ):
        """
        Update GPU state and simulate thermal dynamics.
        
        Args:
            new_utilization: New utilization percentage
            new_vram_used: New VRAM usage in GB
            contexts: List of context IDs on this GPU
            ambient_temp: Ambient temperature
        """
        self.utilization = max(0, min(100, new_utilization))
        self.vram_used = max(0, min(self.vram_total, new_vram_used))
        self.contexts = contexts
        
        # Calculate power draw (simple model)
        idle_power = 50.0
        max_power = 300.0
        self.power_draw = idle_power + (max_power - idle_power) * (self.utilization / 100)
        
        # Simulate thermal dynamics
        # Heat generated by load
        heat_from_load = self.utilization * self.load_heating_coefficient
        
        # Cooling toward ambient
        cooling = (self.temperature - ambient_temp) * self.ambient_cooling_coefficient
        
        # Temperature change with thermal mass smoothing
        delta_t = (heat_from_load - cooling) / self.thermal_mass
        
        # Add some randomness for realism
        noise = random.gauss(0, 0.3)
        
        self.temperature += delta_t + noise
        
        # Clamp to reasonable range
        self.temperature = max(ambient_temp + 5, min(95, self.temperature))
    
    def get_metrics(self) -> GPUMetrics:
        """Get current metrics as GPUMetrics object."""
        # Calculate thermal trend from recent history
        thermal_trend = random.gauss(0, 0.5)  # Simplified
        
        # Calculate thermal headroom
        max_operating_temp = 85.0
        thermal_headroom = max(0, min(1, (max_operating_temp - self.temperature) / 60))
        
        return GPUMetrics(
            gpu_id=self.gpu_id,
            temperature=self.temperature,
            utilization=self.utilization,
            vram_used=self.vram_used,
            vram_total=self.vram_total,
            power_draw=self.power_draw,
            thermal_trend=thermal_trend,
            thermal_headroom=thermal_headroom,
            memory_pressure=self.vram_used / self.vram_total if self.vram_total > 0 else 0,
            rack_id=self.rack_id,
            contexts=self.contexts.copy()
        )


class GPUClusterSimulator:
    """
    Simulates a complete GPU cluster with multiple racks and GPUs.
    """
    
    def __init__(
        self,
        num_gpus: int = 8,
        num_racks: int = 4,
        vram_per_gpu: float = 24.0
    ):
        """
        Initialize GPU cluster simulator.
        
        Args:
            num_gpus: Number of GPUs to simulate
            num_racks: Number of racks
            vram_per_gpu: VRAM per GPU in GB
        """
        self.num_gpus = num_gpus
        self.num_racks = num_racks
        self.gpus: Dict[int, SimulatedGPU] = {}
        
        # Create GPUs distributed across racks
        gpus_per_rack = num_gpus // num_racks
        gpu_idx = 0
        
        for rack_id in range(num_racks):
            # Vary cooling efficiency by rack (some racks cool better)
            rack_cooling = 0.8 + random.random() * 0.4  # 0.8 to 1.2
            
            for i in range(gpus_per_rack if rack_id < num_racks - 1 else num_gpus - gpu_idx):
                # Vary base temperature slightly
                base_temp = 40 + random.random() * 10
                
                self.gpus[gpu_idx] = SimulatedGPU(
                    gpu_id=gpu_idx,
                    rack_id=rack_id,
                    vram_total=vram_per_gpu,
                    base_temp=base_temp,
                    cooling_efficiency=rack_cooling
                )
                gpu_idx += 1
        
        # Simulation state
        self.request_count = 0
        self.start_time = datetime.now()
    
    def get_all_metrics(self) -> List[GPUMetrics]:
        """Get metrics for all GPUs."""
        return [gpu.get_metrics() for gpu in self.gpus.values()]
    
    def get_gpu_metrics(self, gpu_id: int) -> Optional[GPUMetrics]:
        """Get metrics for specific GPU."""
        if gpu_id in self.gpus:
            return self.gpus[gpu_id].get_metrics()
        return None
    
    def update_gpu_workload(
        self,
        gpu_id: int,
        utilization_delta: float,
        vram_delta: float,
        contexts: Optional[List[str]] = None
    ):
        """
        Update workload on a specific GPU.
        
        Args:
            gpu_id: GPU to update
            utilization_delta: Change in utilization
            vram_delta: Change in VRAM usage
            contexts: New context list (optional)
        """
        if gpu_id not in self.gpus:
            return
        
        gpu = self.gpus[gpu_id]
        current_metrics = gpu.get_metrics()
        
        new_util = current_metrics.utilization + utilization_delta
        new_vram = current_metrics.vram_used + vram_delta
        
        if contexts is None:
            contexts = current_metrics.contexts
        
        gpu.update_state(new_util, new_vram, contexts)
    
    def simulate_workload_tick(self, dt_seconds: float = 1.0):
        """
        Advance simulation by one tick.
        
        Args:
            dt_seconds: Time step in seconds
        """
        for gpu in self.gpus.values():
            # Natural cooling when underutilized
            if gpu.utilization < 30:
                gpu.utilization = max(0, gpu.utilization - 2)
            
            # Slight random fluctuations
            gpu.utilization += random.gauss(0, 3)
            gpu.utilization = max(0, min(100, gpu.utilization))
            
            # Update state
            gpu.update_state(
                gpu.utilization,
                gpu.vram_used,
                gpu.contexts
            )
    
    def add_context_to_gpu(self, gpu_id: int, context_id: str, memory_size: float):
        """Add a context to a GPU."""
        if gpu_id in self.gpus:
            if context_id not in self.gpus[gpu_id].contexts:
                self.gpus[gpu_id].contexts.append(context_id)
                self.gpus[gpu_id].vram_used += memory_size
    
    def remove_context_from_gpu(self, gpu_id: int, context_id: str, memory_size: float):
        """Remove a context from a GPU."""
        if gpu_id in self.gpus:
            if context_id in self.gpus[gpu_id].contexts:
                self.gpus[gpu_id].contexts.remove(context_id)
                self.gpus[gpu_id].vram_used = max(0, self.gpus[gpu_id].vram_used - memory_size)
    
